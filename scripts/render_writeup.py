#!/usr/bin/env python3
"""Render WRITEUP.md, the project's essay, from its template and its figure list, and check it.

    python3 -I scripts/render_writeup.py           write WRITEUP.md, once every token resolves
    python3 -I scripts/render_writeup.py --check   exit 1 if WRITEUP.md is not a fresh render
    python3 -I scripts/render_writeup.py --list    each token, its state, its file and its value

No number in the essay is typed. docs/writeup/WRITEUP.template.md is the essay with a {{name}}
token where each figure, verdict and results file's path goes, and docs/writeup/figures.json,
the figure list, says for each token what it is, the kind of results file and the host it is
read from, the field or the computation, and its format. A results file is named by its kind
and host, as a pattern with no commit in it, so a file measured again, whose name carries the
new commit, still resolves; exactly one file must match, or the render stops and names them.
A verdict is the Targets block's own, from scripts/render_results.py's code on the row and parts
scripts/targets.json gives; a target's bar is that row's target value; a byte size or a limit the
essay takes from the code is read from the source file named, by a pattern that must match one
line, so a constant that moves or changes form stops the render.

The render stops, exit 2, on a token the list does not define, an entry of the list the template
never uses, a file kind that names a commit, a token whose kind matches two files, a value that
does not fit its format, a constant whose pattern does not match exactly once, a token that reads
a path its results file lists under not_established (a diagnostic summary's, for what the run's
raw output could not show), and any number in
the template's prose that is not a token, unless it is one of the list's not_results, each with
the reason it is no result (a date, a version, a processor's name). Digits inside a name, as in
AVX2, M4 or Q1, are not numbers to it. HTML comments are notes for whoever edits the template:
they are left out of the page and out of every rule here.

Until the measurements are committed, some kinds of results file do not exist yet, and WRITEUP.md
does not either. Then --check renders what resolves, applies every rule above to it, and exits
EXIT_UNJUDGED, naming how many tokens have no file yet and their kinds: scripts/check.sh reports
that as a skip, a failure under --no-skips, never a pass. Once WRITEUP.md exists, a token with no
file is a failure, and so are a page that differs from a fresh render and a template that still
holds a CUT-OR-CAUSE note. At every stage the essay must run 2,500 to 4,000 words, each token not
yet resolved counted as one, and open with prose before its first section heading, after its
title. What none of this checks is that the prose is true beyond
its figures and verdicts: a sentence can misread a figure that is right, and a number written in
words, such as "six of the seven", is not seen as a number.

Standard library only. tests/scripts/test_render_writeup.py shows each rule failing on a small
tree of its own.
"""

