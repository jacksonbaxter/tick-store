#!/usr/bin/env python3
"""Tests for scripts/render_results.py. Run with:

    python3 -I tests/scripts/test_render_results.py

The script runs as a subprocess on a README and results files under the repo's
gitignored build/ directory. The central test edits one number inside the markers by
hand and requires --check to call the table stale.
"""

import importlib.util
import json
import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
SCRIPT = REPO_ROOT / "scripts" / "render_results.py"
SCRATCH_ROOT = REPO_ROOT / "build" / "test_render_results"

BEGIN = "<!-- results:begin, generated by scripts/render_results.py, do not edit -->"
END = "<!-- results:end -->"
README = f"# Title\n\nBefore.\n\n{BEGIN}\n{END}\n\nAfter.\n"
COMPARE_BEGIN = "<!-- compare:begin, generated by scripts/render_results.py, do not edit -->"
COMPARE_END = "<!-- compare:end -->"
BOTH = f"{README}\n{COMPARE_BEGIN}\n{COMPARE_END}\n\nEnd.\n"


def load_fixtures(name):
    """The validated documents from a validator's own tests, so both stay in step."""
    sys.dont_write_bytecode = True
    path = REPO_ROOT / "tests" / "scripts" / f"{name}.py"
    spec = importlib.util.spec_from_file_location(f"{name}_fixtures", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


FIXTURES = load_fixtures("test_check_results")
COMPARE = load_fixtures("test_check_compare")


class Scratch(unittest.TestCase):
    def setUp(self):
        SCRATCH_ROOT.mkdir(parents=True, exist_ok=True)
        self.dir = Path(tempfile.mkdtemp(dir=SCRATCH_ROOT))
        self.addCleanup(shutil.rmtree, self.dir)
        self.readme = self.dir / "README.md"
        self.readme.write_text(README, encoding="utf-8")
        self.results = self.dir / "results"
        self.results.mkdir()
        self.pins = self.dir / "pins.json"
        self.pins.write_text(json.dumps(FIXTURES.PINS), encoding="utf-8")
        self.compare = self.dir / "compare"
        self.compare.mkdir()
        self.compare_pins = self.dir / "compare-pins.json"
        self.compare_pins.write_text(json.dumps(COMPARE.PINS), encoding="utf-8")
        self.capacity = self.dir / "capacity.json"
        self.capacity.write_text(json.dumps(COMPARE.CAPACITY), encoding="utf-8")

    def add_result(self, host, document=None):
        path = self.results / f"{host}-itch_codec-{FIXTURES.COMMIT[:12]}.json"
        path.write_text(json.dumps(document or FIXTURES.valid_document(host)), encoding="utf-8")

    def render(self, *flags):
        return subprocess.run(
            [sys.executable, "-I", str(SCRIPT), "--readme", str(self.readme), "--results",
             str(self.results), "--pins", str(self.pins), "--compare-results",
             str(self.compare), "--compare-pins", str(self.compare_pins), "--capacity",
             str(self.capacity), *flags],
            capture_output=True, text=True, check=False)


class RenderResultsTest(Scratch):
    def test_tables_go_between_the_markers_and_nothing_else_moves(self):
        self.add_result("Linux")
        self.add_result("macOS")
        self.assertEqual(self.render().returncode, 0)
        text = self.readme.read_text(encoding="utf-8")
        self.assertTrue(text.startswith(f"# Title\n\nBefore.\n\n{BEGIN}\n"))
        self.assertTrue(text.endswith(f"{END}\n\nAfter.\n"))
        self.assertIn("60.00 M", text)
        self.assertIn("20.00", text)

    def test_each_host_gets_its_own_table(self):
        self.add_result("Linux")
        self.add_result("macOS")
        self.render()
        text = self.readme.read_text(encoding="utf-8")
        linux, macos = text.index("**Linux.**"), text.index("**macOS.**")
        self.assertLess(linux, macos)
        between = text[linux:macos]
        self.assertEqual(between.count("| Case |"), 1)
        self.assertIn("40.00", between)
        self.assertIn("Unpinned. No hardware counters.", text[macos:])
        self.assertIn("n/a", text[macos:])

    def test_a_fresh_table_passes_check(self):
        self.add_result("Linux")
        self.render()
        result = self.render("--check")
        self.assertEqual(result.returncode, 0, msg=result.stderr)

    def test_a_hand_edit_inside_the_markers_is_stale(self):
        self.add_result("Linux")
        self.render()
        text = self.readme.read_text(encoding="utf-8")
        self.readme.write_text(text.replace("60.00 M", "99.00 M"), encoding="utf-8")
        result = self.render("--check")
        self.assertEqual(result.returncode, 1)
        self.assertIn("stale or was edited by hand", result.stderr)

    def test_an_edit_outside_the_markers_is_not_stale(self):
        self.add_result("Linux")
        self.render()
        text = self.readme.read_text(encoding="utf-8")
        self.readme.write_text(text.replace("Before.", "Earlier."), encoding="utf-8")
        self.assertEqual(self.render("--check").returncode, 0)

    def test_a_new_results_file_makes_the_table_stale(self):
        self.add_result("Linux")
        self.render()
        self.add_result("macOS")
        self.assertEqual(self.render("--check").returncode, 1)

    def test_a_file_that_fails_validation_is_refused(self):
        document = FIXTURES.valid_document("Linux")
        document["header"]["load_lines"] = []
        self.add_result("Linux", document)
        result = self.render()
        self.assertEqual(result.returncode, 2)
        self.assertIn("failed validation", result.stderr)
        self.assertEqual(self.readme.read_text(encoding="utf-8"), README)

    def test_missing_markers_are_an_error(self):
        self.readme.write_text("# Nothing here\n", encoding="utf-8")
        self.assertEqual(self.render().returncode, 2)

    def test_no_results_says_so(self):
        self.assertEqual(self.render().returncode, 0)
        self.assertIn("No reported results yet.", self.readme.read_text(encoding="utf-8"))



class RenderCompareTest(Scratch):
    """The comparison block: its own markers, one section per host, one table per class."""

    def setUp(self):
        super().setUp()
        self.readme.write_text(BOTH, encoding="utf-8")

    def add_compare(self, host, document=None):
        path = self.compare / f"{host}-{COMPARE.SLICE}-{COMPARE.COMMIT[:12]}.json"
        path.write_text(json.dumps(document or COMPARE.valid_document(host)), encoding="utf-8")

    def block(self):
        text = self.readme.read_text(encoding="utf-8")
        return text[text.index(COMPARE_BEGIN):text.index(COMPARE_END)]

    def test_both_blocks_render_and_nothing_else_moves(self):
        self.add_compare("Linux")
        result = self.render()
        self.assertEqual(result.returncode, 0, msg=result.stderr)
        text = self.readme.read_text(encoding="utf-8")
        self.assertTrue(text.startswith(f"# Title\n\nBefore.\n\n{BEGIN}\n"))
        self.assertTrue(text.endswith(f"{COMPARE_END}\n\nEnd.\n"))
        self.assertIn("No reported results yet.", text[:text.index(COMPARE_BEGIN)])

    def test_every_system_is_in_every_table_tickstore_included(self):
        self.add_compare("Linux")
        self.render()
        block = self.block()
        for label in ("Parquet", "ArcticDB", "QuestDB", "tick-store (parses ITCH)"):
            self.assertIn(f"| {label} |", block)
        self.assertEqual(block.count("| Q1 | tick-store |"), 1)
        self.assertIn("tick-store's ingest holds ITCH parsing", block)

    def test_hosts_and_classes_are_never_in_one_table(self):
        self.add_compare("Linux")
        self.add_compare("macOS")
        self.render()
        block = self.block()
        linux, macos = block.index("**Linux, slice only.**"), block.index("**macOS, slice only.**")
        self.assertLess(linux, macos)
        for section in (block[linux:macos], block[macos:]):
            self.assertEqual(section.count("| Query |"), 1)
            self.assertEqual(section.count("\n| System |"), 2)
            class_a, class_b = section.index("class A:"), section.index("class B:")
            self.assertEqual(section[class_a:class_b].count("\n| System |"), 1)
            self.assertEqual(section[class_b:].count("\n| System |"), 1)

    def test_a_class_b_number_stays_out_of_the_class_a_table(self):
        document = COMPARE.valid_document("Linux")
        COMPARE.b_of(document, "tickstore")["write"]["seconds_median"] = 7.25
        COMPARE.b_of(document, "tickstore")["write"]["records_per_second_median"] = 1000 / 7.25
        self.add_compare("Linux", document)
        result = self.render()
        self.assertEqual(result.returncode, 0, msg=result.stderr)
        block = self.block()
        class_a, class_b = block.index("class A:"), block.index("class B:")
        self.assertNotIn("7.250", block[class_a:class_b])
        self.assertIn("7.250", block[class_b:])

    def test_a_hand_edit_in_the_comparison_is_stale(self):
        self.add_compare("Linux")
        self.render()
        text = self.readme.read_text(encoding="utf-8")
        self.readme.write_text(text.replace("| Q1 | tick-store |", "| Q1 | tick store |"),
                               encoding="utf-8")
        result = self.render("--check")
        self.assertEqual(result.returncode, 1)
        self.assertIn("stale or was edited by hand", result.stderr)

    def test_a_comparison_without_tickstore_is_refused(self):
        document = COMPARE.valid_document("Linux")
        del document["systems"]["tickstore"]
        self.add_compare("Linux", document)
        result = self.render()
        self.assertEqual(result.returncode, 2)
        self.assertIn("comparison results file failed validation", result.stderr)
        self.assertEqual(self.readme.read_text(encoding="utf-8"), BOTH)

    def test_a_full_day_heads_the_block_and_never_shares_a_table_with_a_slice(self):
        document, source = COMPARE.full_day_document()
        document["systems"]["questdb"]["peak_memory"]["vmhwm_bytes_by_process"] = {"java": 10}
        for system in document["systems"].values():
            system["peak_memory"].setdefault("vmhwm_bytes_by_process", {"python3": 10})
        self.add_compare("Linux", source)
        self.add_compare("macOS")
        day = self.compare / f"Linux-{COMPARE.DAY}-full-{COMPARE.COMMIT[:12]}.json"
        day.write_text(json.dumps(document), encoding="utf-8")
        result = self.render()
        self.assertEqual(result.returncode, 0, msg=result.stderr)
        block = self.block()
        full = block.index(f"**Linux, full day {COMPARE.DAY}.**")
        linux = block.index("**Linux, slice only.**")
        macos = block.index("**macOS, slice only.**")
        self.assertLess(full, linux)
        self.assertLess(linux, macos)
        section = block[full:linux]
        self.assertEqual(section.count("| Query |"), 1)
        self.assertIn("the day's source bytes over them", section)
        self.assertNotIn("the slice's source bytes", section)
        self.assertIn("`v` (headline)", section)
        self.assertIn("| QuestDB | 0.00 GiB (`java`)", section)
        self.assertNotIn("Peak memory", block[linux:])

    def test_comparison_files_need_their_markers(self):
        self.readme.write_text(README, encoding="utf-8")
        self.add_compare("Linux")
        result = self.render()
        self.assertEqual(result.returncode, 2)
        self.assertIn("comparison markers are not in", result.stderr)


if __name__ == "__main__":
    unittest.main()
