class RenderTargetsTest(Scratch):
    """The targets block: every verdict computed from a results file and the target."""

    def setUp(self):
        super().setUp()
        self.results_md.write_text(WITH_TARGETS, encoding="utf-8")
        self.write_targets(TARGET_ROWS)
        (self.tree / "results").mkdir(parents=True)
        self.day = self.tree / "results" / "day-0123.json"
        self.day.write_text(json.dumps(TARGET_DOCUMENT), encoding="utf-8")

    def write_targets(self, rows):
        self.targets.write_text(json.dumps({"schema": "t", "rows": rows}), encoding="utf-8")

    def block(self):
        text = self.results_md.read_text(encoding="utf-8")
        return text[text.index(TARGETS_BEGIN):text.index(TARGETS_END)]

    def row(self, ident, host):
        return next(line for line in self.block().splitlines()
                    if line.startswith(f"| {ident} | {host} |"))

    def test_each_verdict_is_computed_from_the_value_and_the_target(self):
        result = self.render()
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn("| 7.25 ms | missed | `results/day-0123.json` |", self.row("T-1", "Linux"))
        self.assertIn("at most 5.00 ms", self.row("T-1", "Linux"))
        self.assertIn("| 7.25 ms | met |", self.row("T-2", "macOS"))
        self.assertIn("one: 2.0 bits; two: 4.0 bits | met on (one); missed on (two)",
                      self.row("T-3", "any"))
        self.assertIn("2.000 against 4.000 | met", self.row("T-4", "Linux"))

    def test_rows_with_no_figure_say_why(self):
        self.render()
        self.assertIn("| no figure | not judged: it runs on Linux only | none |",
                      self.row("T-5", "macOS"))
        self.assertIn("not judged: no file was kept", self.row("T-6", "Linux"))

    def test_the_headline_is_read_from_the_file(self):
        document = json.loads(json.dumps(TARGET_DOCUMENT))
        document["systems"]["s"]["headline_variant"] = "x"
        self.day.write_text(json.dumps(document), encoding="utf-8")
        self.render()
        self.assertIn("| 1.00 ms | met |", self.row("T-1", "Linux"))

    def test_a_hand_edited_value_is_stale(self):
        self.render()
        text = self.results_md.read_text(encoding="utf-8")
        self.results_md.write_text(text.replace("| 7.25 ms | missed |", "| 4.25 ms | met |", 1),
                               encoding="utf-8")
        result = self.render("--check")
        self.assertEqual(result.returncode, 1, result.stderr)
        self.assertIn("stale or was edited by hand", result.stderr)

    def test_a_changed_results_value_is_stale(self):
        self.render()
        document = json.loads(json.dumps(TARGET_DOCUMENT))
        document["systems"]["s"]["variants"]["h"]["ms"] = 4.0
        self.day.write_text(json.dumps(document), encoding="utf-8")
        result = self.render("--check")
        self.assertEqual(result.returncode, 1, result.stderr)

    def test_a_missing_file_fails(self):
        self.render()
        self.day.unlink()
        result = self.render("--check")
        self.assertEqual(result.returncode, 2, result.stderr)
        self.assertIn("T-1 on Linux: no results file matches results/day-*.json", result.stderr)

    def test_a_field_not_in_the_file_fails(self):
        rows = json.loads(json.dumps(TARGET_ROWS))
        rows[0]["parts"][0]["value"]["path"][-1] = "seconds"
        self.write_targets(rows)
        result = self.render()
        self.assertEqual(result.returncode, 2, result.stderr)
        self.assertIn("no 'seconds' on the path", result.stderr)
        self.assertEqual(self.results_md.read_text(encoding="utf-8"), WITH_TARGETS)

    def test_two_files_for_one_pattern_fail(self):
        (self.tree / "results" / "day-4567.json").write_text(json.dumps(TARGET_DOCUMENT),
                                                            encoding="utf-8")
        result = self.render()
        self.assertEqual(result.returncode, 2, result.stderr)
        self.assertIn("matches 2 files", result.stderr)

    def test_targets_need_their_markers_and_the_markers_their_targets(self):
        self.results_md.write_text(RESULTS_MD, encoding="utf-8")
        self.assertEqual(self.render().returncode, 2)
        self.results_md.write_text(WITH_TARGETS, encoding="utf-8")
        self.targets.unlink()
        result = self.render()
        self.assertEqual(result.returncode, 2)
        self.assertIn("both or neither", result.stderr)

    def test_the_repos_own_targets_cover_every_benchmarks_target_and_host(self):
        rows = json.loads((REPO_ROOT / "scripts" / "targets.json").read_text(encoding="utf-8"))
        found = {(row["id"], row["host"]) for row in rows["rows"]}
        text = (REPO_ROOT / "BENCHMARKS.md").read_text(encoding="utf-8")
        hosts = {"macOS": {"macOS"}, "Linux": {"Linux"}, "Both": {"macOS", "Linux"},
                 "macOS, Linux": {"macOS", "Linux"}}
        for line in text.splitlines():
            cells = [cell.strip() for cell in line.strip("|").split("|")]
            ident = cells[0]
            if not any(ident.startswith(prefix) for prefix in ("G-", "CR-", "DS-", "WT-", "QL-")):
                continue
            if not ident.split("-")[1].isdigit() or len(cells) < 3:
                continue
            if ident.startswith(("DS-", "WT-", "QL-")) and cells[2] in hosts:
                wanted = {(ident, host) for host in hosts[cells[2]]}
            elif ident.startswith(("G-", "CR-")):
                wanted = {(ident, host) for host in ("any", "Linux") if (ident, host) in found}
                self.assertTrue(wanted, f"{ident} has no row")
            else:
                continue
            self.assertLessEqual(wanted, found, f"{ident}: rows {wanted - found} missing")


