#!/usr/bin/env python3
"""Tests for scripts/render_results.py. Run with:

    python3 -I tests/scripts/test_render_results.py

The script runs as a subprocess on a RESULTS.md, a README and results files under the
repo's gitignored build/ directory. The central tests edit one number inside the markers of
either file by hand and require --check to call the table stale.
"""

import importlib.util
import json
import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
SCRIPT = REPO_ROOT / "scripts" / "render_results.py"
SCRATCH_ROOT = REPO_ROOT / "build" / "test_render_results"

BEGIN = "<!-- results:begin, generated by scripts/render_results.py, do not edit -->"
END = "<!-- results:end -->"
RESULTS_MD = f"# Title\n\nBefore.\n\n{BEGIN}\n{END}\n\nAfter.\n"
# A README with no headline, as with no targets.json.
PLAIN_README = "# Title\n\nNo tables here.\n"
COMPARE_BEGIN = "<!-- compare:begin, generated by scripts/render_results.py, do not edit -->"
COMPARE_END = "<!-- compare:end -->"
BOTH = f"{RESULTS_MD}\n{COMPARE_BEGIN}\n{COMPARE_END}\n\nEnd.\n"


def load_fixtures(name):
    """The validated documents from a validator's own tests, so both stay in step."""
    sys.dont_write_bytecode = True
    path = REPO_ROOT / "tests" / "scripts" / f"{name}.py"
    spec = importlib.util.spec_from_file_location(f"{name}_fixtures", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


FIXTURES = load_fixtures("test_check_results")
COMPARE = load_fixtures("test_check_compare")
_SPEC = importlib.util.spec_from_file_location("render_results", SCRIPT)
RENDER = importlib.util.module_from_spec(_SPEC)
_SPEC.loader.exec_module(RENDER)


class Scratch(unittest.TestCase):
    def setUp(self):
        SCRATCH_ROOT.mkdir(parents=True, exist_ok=True)
        self.dir = Path(tempfile.mkdtemp(dir=SCRATCH_ROOT))
        self.addCleanup(shutil.rmtree, self.dir)
        self.results_md = self.dir / "RESULTS.md"
        self.results_md.write_text(RESULTS_MD, encoding="utf-8")
        self.readme = self.dir / "README.md"
        self.readme.write_text(PLAIN_README, encoding="utf-8")
        self.results = self.dir / "results"
        self.results.mkdir()
        self.pins = self.dir / "pins.json"
        self.pins.write_text(json.dumps(FIXTURES.PINS), encoding="utf-8")
        self.compare = self.dir / "compare"
        self.compare.mkdir()
        self.compare_pins = self.dir / "compare-pins.json"
        self.compare_pins.write_text(json.dumps(COMPARE.PINS), encoding="utf-8")
        self.capacity = self.dir / "capacity.json"
        self.capacity.write_text(json.dumps(COMPARE.CAPACITY), encoding="utf-8")
        # No targets block unless a test writes the definitions and the markers.
        self.targets = self.dir / "targets.json"
        self.tree = self.dir / "tree"

    def add_result(self, host, document=None):
        path = self.results / f"{host}-itch_codec-{FIXTURES.COMMIT[:12]}.json"
        path.write_text(json.dumps(document or FIXTURES.valid_document(host)), encoding="utf-8")

    def render(self, *flags):
        # The fixtures that state no protocol stand for the committed protocol 1 files, which
        # the validator knows by their bytes (review RV-6).
        COMPARE.pin_protocol_1(self.compare_pins, self.compare)
        return subprocess.run(
            [sys.executable, "-I", str(SCRIPT), "--readme", str(self.readme), "--results-md",
             str(self.results_md), "--results",
             str(self.results), "--pins", str(self.pins), "--compare-results",
             str(self.compare), "--compare-pins", str(self.compare_pins), "--capacity",
             str(self.capacity), "--targets", str(self.targets), "--targets-root",
             str(self.tree), *flags],
            capture_output=True, text=True, check=False)


class RenderResultsTest(Scratch):
    def test_tables_go_between_the_markers_and_nothing_else_moves(self):
        self.add_result("Linux")
        self.add_result("macOS")
        self.assertEqual(self.render().returncode, 0)
        text = self.results_md.read_text(encoding="utf-8")
        self.assertTrue(text.startswith(f"# Title\n\nBefore.\n\n{BEGIN}\n"))
        self.assertTrue(text.endswith(f"{END}\n\nAfter.\n"))
        self.assertIn("60.00 M", text)
        self.assertIn("20.00", text)

    def test_each_host_gets_its_own_table(self):
        self.add_result("Linux")
        self.add_result("macOS")
        self.render()
        text = self.results_md.read_text(encoding="utf-8")
        linux, macos = text.index("**Linux.**"), text.index("**macOS.**")
        self.assertLess(linux, macos)
        between = text[linux:macos]
        self.assertEqual(between.count("| Case |"), 1)
        self.assertIn("40.00", between)
        self.assertIn("Unpinned. No hardware counters.", text[macos:])
        self.assertIn("n/a", text[macos:])

    def test_a_fresh_table_passes_check(self):
        self.add_result("Linux")
        self.render()
        result = self.render("--check")
        self.assertEqual(result.returncode, 0, msg=result.stderr)

    def test_a_hand_edit_inside_the_markers_is_stale(self):
        self.add_result("Linux")
        self.render()
        text = self.results_md.read_text(encoding="utf-8")
        self.results_md.write_text(text.replace("60.00 M", "99.00 M"), encoding="utf-8")
        result = self.render("--check")
        self.assertEqual(result.returncode, 1)
        self.assertIn("stale or was edited by hand", result.stderr)

    def test_an_edit_outside_the_markers_is_not_stale(self):
        self.add_result("Linux")
        self.render()
        text = self.results_md.read_text(encoding="utf-8")
        self.results_md.write_text(text.replace("Before.", "Earlier."), encoding="utf-8")
        self.assertEqual(self.render("--check").returncode, 0)

    def test_a_new_results_file_makes_the_table_stale(self):
        self.add_result("Linux")
        self.render()
        self.add_result("macOS")
        self.assertEqual(self.render("--check").returncode, 1)

    def test_a_file_that_fails_validation_is_refused(self):
        document = FIXTURES.valid_document("Linux")
        document["header"]["load_lines"] = []
        self.add_result("Linux", document)
        result = self.render()
        self.assertEqual(result.returncode, 2)
        self.assertIn("failed validation", result.stderr)
        self.assertEqual(self.results_md.read_text(encoding="utf-8"), RESULTS_MD)

    def test_missing_markers_are_an_error(self):
        self.results_md.write_text("# Nothing here\n", encoding="utf-8")
        self.assertEqual(self.render().returncode, 2)

    def test_no_results_says_so(self):
        self.assertEqual(self.render().returncode, 0)
        self.assertIn("No reported results yet.", self.results_md.read_text(encoding="utf-8"))

    # Values, not messages: a real-data column file gets a row a case, and a kernel file a
    # row a kernel and set, the median across its widths.

    def add_named(self, host, benchmark, document):
        path = self.results / f"{host}-{benchmark}-{FIXTURES.COMMIT[:12]}.json"
        path.write_text(json.dumps(document), encoding="utf-8")

    def kernel_document(self, host):
        document = FIXTURES.seeded_document(host)
        row = document["results"][0]
        rows = []
        for width, rate in ((1, 3e9), (13, 1e9), (64, 2e9)):
            copied = json.loads(json.dumps(row))
            copied["case"] = f"pfor_delta_two_pass/w={width}/scalar"
            copied["throughput"]["values_per_second"]["median"] = rate
            if host == "Linux":
                copied["counters"]["per_value"]["cycles"] = 3.5e9 / rate
            rows.append(copied)
        document["results"] = rows
        header = document["header"]
        header["load_lines"] = header["load_lines"] * len(rows)
        if host == "Linux":
            header["sibling_busy_percent"]["cases"] = {r["case"]: 0.5 for r in rows}
        return document

    def test_a_column_file_gets_a_row_a_case_in_values(self):
        self.add_named("Linux", "column_decode", FIXTURES.column_document("Linux"))
        result = self.render()
        self.assertEqual(result.returncode, 0, msg=result.stderr)
        text = self.results_md.read_text(encoding="utf-8")
        self.assertIn("**Linux, real-data column decodes of the slice.**", text)
        row = next(line for line in text.splitlines() if "store_decode/add_price" in line)
        cells = [cell.strip() for cell in row.strip("|").split("|")]
        # 6e7 values a second: 16.667 ns a value, 480 MB/s of 8-byte values, 6.40 bits.
        self.assertEqual(cells[3:7], ["3,000", "6.40", "16.667", "480"])

    def test_a_kernel_file_gets_the_median_across_widths(self):
        for host in ("Linux", "macOS"):
            with self.subTest(host=host):
                self.add_named(host, "simd_kernel", self.kernel_document(host))
        result = self.render()
        self.assertEqual(result.returncode, 0, msg=result.stderr)
        text = self.results_md.read_text(encoding="utf-8")
        rows = [line for line in text.splitlines() if "`pfor_delta_two_pass`" in line]
        self.assertEqual(len(rows), 2)
        linux = [cell.strip() for cell in rows[0].strip("|").split("|")]
        self.assertEqual(linux[3:8], ["3", "2.00", "1.00 to 3.00", "1.00%", "1.750"])
        macos = [cell.strip() for cell in rows[1].strip("|").split("|")]
        self.assertEqual(macos[7], "n/a")
        self.assertLess(text.index("**Linux, decode kernels"), text.index("**macOS, decode kernels"))

    def test_value_files_never_join_the_message_table(self):
        self.add_result("Linux")
        self.add_named("Linux", "column_decode", FIXTURES.column_document("Linux"))
        self.render()
        text = self.results_md.read_text(encoding="utf-8")
        message_table = text[text.index("**Linux.**"):text.index("**Linux, real-data")]
        self.assertNotIn("store_decode", message_table)



